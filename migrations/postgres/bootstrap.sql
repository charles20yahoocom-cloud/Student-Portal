CREATE TABLE users (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('student', 'dean', 'admin', 'faculty', 'registrar')), full_name TEXT NOT NULL, is_active INTEGER DEFAULT 1, totp_secret TEXT, totp_enabled INTEGER DEFAULT 0, failed_login_attempts INTEGER DEFAULT 0, locked_until TEXT, last_login TEXT, created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), updated_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), profile_picture TEXT, picture_updated_at TEXT, department_id INTEGER);

CREATE TABLE students (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER UNIQUE NOT NULL, student_no TEXT UNIQUE NOT NULL, first_name TEXT NOT NULL, middle_name TEXT, last_name TEXT NOT NULL, gender TEXT CHECK(gender IN ('M', 'F', 'Other')), date_of_birth TEXT, program_code TEXT NOT NULL, year_level INTEGER NOT NULL CHECK(year_level BETWEEN 1 AND 4), status TEXT DEFAULT 'active' CHECK(status IN ('active', 'inactive', 'graduated', 'dropped', 'suspended')), profile_picture TEXT, picture_updated_at TEXT, enrollment_date TEXT, expected_graduation TEXT, created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), updated_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), section TEXT);

CREATE TABLE departments (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT UNIQUE NOT NULL, name TEXT NOT NULL, hod_user_id INTEGER, created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));

CREATE TABLE semesters (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, school_year TEXT NOT NULL, start_date TEXT, end_date TEXT, is_active INTEGER DEFAULT 0, grade_encoding_deadline TEXT, created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), UNIQUE(name, school_year));

CREATE TABLE programs (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT UNIQUE NOT NULL, name TEXT NOT NULL, department_id INTEGER NOT NULL, total_units INTEGER NOT NULL, total_years INTEGER DEFAULT 4, created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));

CREATE TABLE curriculum_templates (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, program_code TEXT NOT NULL, program_name TEXT NOT NULL, total_years INTEGER DEFAULT 4, total_semesters INTEGER DEFAULT 8, is_active INTEGER DEFAULT 1, created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));

CREATE TABLE curriculum_items (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, template_id INTEGER NOT NULL, semester_number INTEGER NOT NULL CHECK(semester_number BETWEEN 1 AND 8), course_code TEXT NOT NULL, course_name TEXT NOT NULL, credits INTEGER NOT NULL, course_type TEXT DEFAULT 'regular', display_order INTEGER DEFAULT 0, lec_hours INTEGER, lab_hours INTEGER, prerequisite TEXT, UNIQUE(template_id, course_code));

CREATE TABLE student_curriculum (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER NOT NULL, template_id INTEGER NOT NULL, enrolled_year INTEGER NOT NULL, current_semester INTEGER DEFAULT 1, status TEXT DEFAULT 'active', UNIQUE(student_id, template_id));

CREATE TABLE courses (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT NOT NULL, name TEXT NOT NULL, credits INTEGER NOT NULL, department_id INTEGER, created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));

CREATE TABLE course_offerings (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, course_code TEXT NOT NULL, course_name TEXT NOT NULL, section TEXT NOT NULL, semester_id INTEGER NOT NULL, instructor_id INTEGER, credits INTEGER NOT NULL, max_enrollment INTEGER, created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), program_code TEXT, UNIQUE(course_code, section, semester_id));

CREATE TABLE enrollments (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER NOT NULL, offering_id INTEGER NOT NULL, enrolled_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), status TEXT DEFAULT 'enrolled' CHECK(status IN ('enrolled', 'dropped', 'completed')), UNIQUE(student_id, offering_id));

CREATE TABLE grades (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, enrollment_id INTEGER NOT NULL, student_id INTEGER NOT NULL, course_code TEXT NOT NULL, semester_id INTEGER NOT NULL, grade_value TEXT, grade_points REAL, credits INTEGER NOT NULL, remarks TEXT, encoded_by INTEGER NOT NULL, encoded_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), modified_at TEXT, is_final INTEGER DEFAULT 0, UNIQUE(enrollment_id));

CREATE TABLE grade_scale (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, letter_grade TEXT NOT NULL UNIQUE, min_score REAL NOT NULL, max_score REAL NOT NULL, grade_points REAL NOT NULL, description TEXT, is_passing INTEGER DEFAULT 1);

CREATE TABLE grade_releases (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, course_code TEXT, semester_id INTEGER NOT NULL, release_type TEXT NOT NULL CHECK(release_type IN ('scheduled', 'manual')), scheduled_at TEXT, released_at TEXT, released_by INTEGER, status TEXT DEFAULT 'draft' CHECK(status IN ('draft', 'scheduled', 'released')), created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));

CREATE TABLE prospectus_entries (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER NOT NULL, course_id INTEGER NOT NULL, semester_id INTEGER NOT NULL, planned_grade TEXT, actual_grade TEXT, status TEXT DEFAULT 'planned' CHECK(status IN ('planned', 'enrolled', 'completed')), encoded_by INTEGER, created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), updated_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));

CREATE TABLE notifications (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL, title TEXT NOT NULL, message TEXT NOT NULL, type TEXT NOT NULL, read_at TEXT, created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));

CREATE TABLE backup_codes (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL, code_hash TEXT NOT NULL, used_at TEXT, created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));

CREATE TABLE grade_audit_log (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER NOT NULL, course_code TEXT NOT NULL, semester_id INTEGER NOT NULL, old_grade TEXT, new_grade TEXT NOT NULL, encoded_by INTEGER NOT NULL, encoded_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), reason TEXT);

CREATE TABLE transcripts (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER NOT NULL, request_date TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), issued_date TEXT, issued_by INTEGER, status TEXT DEFAULT 'pending' CHECK(status IN ('pending', 'processing', 'completed', 'rejected')), purpose TEXT, copies INTEGER DEFAULT 1, verification_code TEXT UNIQUE, created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));

CREATE TABLE password_resets (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL, email TEXT NOT NULL, code_hash TEXT NOT NULL, attempts INTEGER NOT NULL DEFAULT 0, used_at TEXT, expires_at TEXT NOT NULL, created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));

