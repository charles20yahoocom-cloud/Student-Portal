  remarks TEXT,
  updated_by INTEGER NOT NULL,
  updated_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
  UNIQUE(student_id, course_code)
);

