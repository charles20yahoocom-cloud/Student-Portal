const test = require('node:test');
const assert = require('node:assert/strict');
const Database = require('better-sqlite3');
const {
  postgresForeignKeyStatements,
  toPostgresPlaceholders,
  toPostgresSchemaSql,
  toPostgresSql,
  withoutPostgresForeignKeys
} = require('../src/config/sql-compat');
const { assertMigratedSource, orderedTables } = require('../scripts/migrate-sqlite-to-postgres');

test('converts positional placeholders without changing quoted question marks', () => {
  const sql = "SELECT '?' AS marker FROM users WHERE id = ? -- ignored ?\nAND email = ?";
  assert.equal(
    toPostgresPlaceholders(sql),
    "SELECT '?' AS marker FROM users WHERE id = $1 -- ignored ?\nAND email = $2"
  );
});

test('translates SQLite ignore, date arithmetic, and parameterized interval expressions', () => {
  assert.equal(
    toPostgresSql('INSERT OR IGNORE INTO departments (code, name) VALUES (?, ?)'),
    'INSERT INTO departments (code, name) VALUES ($1, $2) ON CONFLICT DO NOTHING'
  );
  assert.equal(
    toPostgresSql("SELECT datetime('now', '-15 minutes') WHERE id = ?"),
    "SELECT to_char((CURRENT_TIMESTAMP - INTERVAL '15 minutes') AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') WHERE id = $1"
  );
  assert.equal(
    toPostgresSql("SELECT datetime('now', ?) WHERE id = ?"),
    "SELECT to_char((CURRENT_TIMESTAMP + ($1::interval)) AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') WHERE id = $2"
  );
});

test('translates SQLite identity and timestamp defaults for PostgreSQL schema creation', () => {
  assert.equal(
    toPostgresSchemaSql("CREATE TABLE users (id INTEGER PRIMARY KEY AUTOINCREMENT, created_at TEXT DEFAULT (datetime('now')))"),
    "CREATE TABLE users (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')))"
  );
});

test('separates table and inline foreign keys from PostgreSQL table creation', () => {
  const sqlite = new Database(':memory:');
  try {
    sqlite.exec(`
      CREATE TABLE parent (id INTEGER PRIMARY KEY);
      CREATE TABLE child (
        id INTEGER PRIMARY KEY,
        inline_parent INTEGER REFERENCES parent(id),
        table_parent INTEGER,
        FOREIGN KEY (table_parent) REFERENCES parent(id)
      );
    `);
    const table = sqlite.prepare(
      "SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name = 'child'"
    ).get();
    const createTable = withoutPostgresForeignKeys(table.sql);
    assert.doesNotMatch(createTable, /REFERENCES|FOREIGN KEY/i);
    assert.equal(postgresForeignKeyStatements(sqlite, table).length, 2);
    assert.match(postgresForeignKeyStatements(sqlite, table)[0], /REFERENCES "parent" \("id"\)/);
  } finally {
    sqlite.close();
  }
});

test('orders imported tables by foreign-key dependencies', () => {
  const source = new Database(':memory:');
  try {
    source.exec(`
      CREATE TABLE child (id INTEGER PRIMARY KEY, parent_id INTEGER REFERENCES parent(id));
      CREATE TABLE parent (id INTEGER PRIMARY KEY);
    `);
    const tables = [
      { name: 'child', sql: 'CREATE TABLE child (...)' },
      { name: 'parent', sql: 'CREATE TABLE parent (...)' }
    ];
    assert.deepEqual(orderedTables(source, tables).map((table) => table.name), ['parent', 'child']);
  } finally {
    source.close();
  }
});

test('refuses SQLite sources with foreign-key violations', () => {
  const source = new Database(':memory:');
  try {
    source.pragma('foreign_keys = OFF');
    source.exec(`
      CREATE TABLE parent (id INTEGER PRIMARY KEY);
      CREATE TABLE child (parent_id INTEGER REFERENCES parent(id));
      INSERT INTO child (parent_id) VALUES (99);
    `);
    assert.throws(() => assertMigratedSource(source), /foreign-key violations/);
  } finally {
    source.close();
  }
});

test('refuses SQLite sources with missing migration records', () => {
  const source = new Database(':memory:');
  try {
    source.exec('CREATE TABLE schema_migrations (filename TEXT PRIMARY KEY, applied_at TEXT)');
    assert.throws(() => assertMigratedSource(source), /missing migrations/);
  } finally {
    source.close();
  }
});
