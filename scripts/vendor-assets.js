// Downloads the front-end assets the portal used to load from CDNs so the
// LAN demo works with no internet. Re-run only when you intentionally bump a
// version; the downloaded files are committed with the project.
//
//   node scripts/vendor-assets.js
//
// Outputs (inside src/public):
//   js/tailwind.js        Tailwind Play CDN 3.4.17
//   css/fonts.css         @font-face rules rewritten to /fonts/*
//   fonts/*.woff2         Inter 400/500/600/700 + Playfair Display 600/700
//
// The login animation uses the local js/motion-lite.js (no download needed).
const fs = require('fs');
const path = require('path');

const PUBLIC = path.join(__dirname, '..', 'src', 'public');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ' +
  '(KHTML, like Gecko) Chrome/120.0 Safari/537.36';

const TAILWIND_URL = 'https://cdn.tailwindcss.com/3.4.17';
const FONTS_URL = 'https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700' +
  '&family=Playfair+Display:wght@600;700&display=swap';

async function fetchOk(url, headers = {}) {
  const res = await fetch(url, { headers });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return res;
}

async function fetchBuffer(url, headers) {
  return Buffer.from(await (await fetchOk(url, headers)).arrayBuffer());
}

async function main() {
  fs.mkdirSync(path.join(PUBLIC, 'js'), { recursive: true });
  fs.mkdirSync(path.join(PUBLIC, 'css'), { recursive: true });
  fs.mkdirSync(path.join(PUBLIC, 'fonts'), { recursive: true });

  const tailwind = await fetchBuffer(TAILWIND_URL);
  fs.writeFileSync(path.join(PUBLIC, 'js', 'tailwind.js'), tailwind);
  console.log(`tailwind.js      ${tailwind.length} bytes`);

  let css = await (await fetchOk(FONTS_URL, { 'User-Agent': UA })).text();
  const urls = [...new Set(
    [...css.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g)].map((m) => m[1])
  )];

  for (const url of urls) {
    const name = path.basename(new URL(url).pathname);
    const buffer = await fetchBuffer(url);
    fs.writeFileSync(path.join(PUBLIC, 'fonts', name), buffer);
    css = css.split(url).join(`/fonts/${name}`);
  }

  css = '/* Self-hosted Google Fonts: Inter 400/500/600/700, Playfair Display 600/700.\n' +
    '   Generated by scripts/vendor-assets.js - do not edit by hand. */\n' + css;
  fs.writeFileSync(path.join(PUBLIC, 'css', 'fonts.css'), css);
  console.log(`fonts.css        ${urls.length} woff2 files`);
}

main().catch((err) => {
  console.error('Asset download failed:', err.message);
  process.exit(1);
});
