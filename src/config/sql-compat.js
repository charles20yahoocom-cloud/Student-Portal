function toPostgresPlaceholders(sql) {
  let output = '';
  let parameter = 0;
  let state = 'normal';

  for (let i = 0; i < sql.length; i++) {
    const char = sql[i];
    const next = sql[i + 1];

    if (state === 'line-comment') {
      output += char;
      if (char === '\n') state = 'normal';
      continue;
    }
    if (state === 'block-comment') {
      output += char;
      if (char === '*' && next === '/') {
        output += next;
        i++;
        state = 'normal';
      }
      continue;
    }
    if (state === 'single' || state === 'double' || state === 'backtick') {
      output += char;
      const closing = state === 'single' ? "'" : state === 'double' ? '"' : '`';
      if (char === closing && next === closing) {
        output += next;
        i++;
      } else if (char === closing) {
        state = 'normal';
      }
      continue;
    }

    if (char === '-' && next === '-') {
      output += '--';
      i++;
      state = 'line-comment';
    } else if (char === '/' && next === '*') {
      output += '/*';
      i++;
      state = 'block-comment';
    } else if (char === "'") {
      output += char;
      state = 'single';
    } else if (char === '"') {
      output += char;
      state = 'double';
    } else if (char === '`') {
      output += char;
      state = 'backtick';
    } else if (char === '?') {
      output += `$${++parameter}`;
    } else {
      output += char;
    }
  }

  return output;
}

function toPostgresSql(sql) {
  let output = String(sql)
    .replace(/\bINSERT\s+OR\s+IGNORE\s+INTO\b/gi, 'INSERT INTO')
    .replace(/\bdatetime\s*\(\s*(['"])now\1\s*,\s*(['"])([+-]\d+\s+\w+)\2\s*\)/gi, (_match, _quote, _intervalQuote, interval) => {
      const sign = interval[0] === '-' ? '-' : '+';
      return `to_char((CURRENT_TIMESTAMP ${sign} INTERVAL '${interval.slice(1)}') AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')`;
    })
    .replace(/\bdatetime\s*\(\s*(['"])now\1\s*,\s*\?\s*\)/gi, "to_char((CURRENT_TIMESTAMP + (?::interval)) AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')")
    .replace(/\bdatetime\s*\(\s*(['"])now\1\s*\)/gi, "to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')");

  const ignoreConflict = /^\s*INSERT\s+INTO\b/i.test(output) &&
    /^\s*INSERT\s+OR\s+IGNORE\s+INTO\b/i.test(String(sql));
  if (ignoreConflict && !/\bON\s+CONFLICT\b/i.test(output)) {
    output = output.replace(/;\s*$/, '');
    output += ' ON CONFLICT DO NOTHING';
  }

  return toPostgresPlaceholders(output);
}

function toPostgresSchemaSql(sql) {
  return String(sql)
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bAUTOINCREMENT\b/gi, '')
    .replace(/\bdatetime\s*\(\s*(['"])now\1\s*\)/gi, "to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')");
}

function withoutPostgresForeignKeys(sql) {
  const source = String(sql);
  const opening = source.indexOf('(');
  if (opening < 0) return source;

  let depth = 0;
  let closing = -1;
  let quote = null;
  for (let i = opening; i < source.length; i++) {
    const char = source[i];
    const next = source[i + 1];
    if (quote) {
      if (char === quote && next === quote) i++;
      else if (char === quote) quote = null;
      continue;
    }
    if (char === "'" || char === '"' || char === '`') {
      quote = char;
    } else if (char === '(') {
      depth++;
    } else if (char === ')' && --depth === 0) {
      closing = i;
      break;
    }
  }
  if (closing < 0) throw new Error('Could not parse table schema while separating foreign keys.');

  const definitions = [];
  let start = opening + 1;
  depth = 0;
  quote = null;
  for (let i = start; i < closing; i++) {
    const char = source[i];
    const next = source[i + 1];
    if (quote) {
      if (char === quote && next === quote) i++;
      else if (char === quote) quote = null;
      continue;
    }
    if (char === "'" || char === '"' || char === '`') {
      quote = char;
    } else if (char === '(') {
      depth++;
    } else if (char === ')') {
      depth--;
    } else if (char === ',' && depth === 0) {
      definitions.push(source.slice(start, i).trim());
      start = i + 1;
    }
  }
  definitions.push(source.slice(start, closing).trim());

  const withoutTableConstraints = definitions
    .filter((definition) => !/^(?:CONSTRAINT\s+(?:"[^"]+"|\w+)\s+)?FOREIGN\s+KEY\b/i.test(definition))
    .map((definition) => definition.replace(
      /\s+REFERENCES\s+(?:"[^"]+"|[\w.]+)\s*\([^)]*\)(?:\s+MATCH\s+\w+)?(?:\s+ON\s+(?:DELETE|UPDATE)\s+(?:NO\s+ACTION|SET\s+NULL|SET\s+DEFAULT|CASCADE|RESTRICT))*/gi,
      ''
    ));

  return `${source.slice(0, opening + 1)}${withoutTableConstraints.join(', ')}${source.slice(closing)}`;
}

function postgresForeignKeyStatements(source, table) {
  const quoteIdentifier = (identifier) => `"${String(identifier).replace(/"/g, '""')}"`;
  return source.pragma(`foreign_key_list(${quoteIdentifier(table.name)})`).map((foreignKey) => {
    const name = quoteIdentifier(`fk_${table.name}_${foreignKey.id}`);
    const action = (value) => String(value).toUpperCase() === 'NO ACTION' ? '' : ` ON ${value}`;
    return `ALTER TABLE ${quoteIdentifier(table.name)} ADD CONSTRAINT ${name} ` +
      `FOREIGN KEY (${quoteIdentifier(foreignKey.from)}) ` +
      `REFERENCES ${quoteIdentifier(foreignKey.table)} (${quoteIdentifier(foreignKey.to)})` +
      `${action(foreignKey.on_update)}${action(foreignKey.on_delete)}`;
  });
}

